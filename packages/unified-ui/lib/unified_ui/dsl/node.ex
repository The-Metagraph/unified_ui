  @moduledoc """
  Baseline authored node shape for `UnifiedUi` widgets, forms, and layouts.
  """

  @type family ::
          :foundational
          | :input
          | :navigation
          | :forms
          | :layout
          | :data
          | :feedback
          | :advanced
          | :overlay
          | :display
          | :canvas

  @type t :: %__MODULE__{
          __identifier__: atom() | nil,
          id: atom() | nil,
          family: family() | nil,
          kind: atom() | nil,
          value: String.t() | nil,
          label: String.t() | nil,
          target: String.t() | atom() | nil,
          source: String.t() | nil,
          name: atom() | String.t() | nil,
          description: String.t() | nil,
          authored_ref: [atom()] | nil,
          annotations: keyword(),
          tags: [atom()],
          variant: atom() | nil,
          tone: atom() | nil,
          style_refs: [atom()],
          accessibility_label: String.t() | nil,
          accessibility_description: String.t() | nil,
          action_intent: atom() | nil,
          navigation_target: String.t() | nil,
          disabled?: boolean(),
          set: atom() | nil,
          fallback_text: String.t() | nil,
          alt_text: String.t() | nil,
          media_type: String.t() | nil,
          fit: atom() | nil,
          role: atom() | nil,
          presentation: atom() | nil,
          summary: String.t() | nil,
          emphasis: atom() | nil,
          external?: boolean() | nil,
          target_kind: atom() | nil,
          orientation: atom() | nil,
          decorative?: boolean() | nil,
          size: atom() | nil,
          grow: integer() | nil,
          placeholder: String.t() | nil,
          multiline?: boolean() | nil,
          input_mode: atom() | nil,
          options: keyword(),
          active_item: atom() | nil,
          multiple?: boolean() | nil,
          field_name: atom() | nil,
          value_path: [atom()] | nil,
          default_value: term(),
          submit_intent: atom() | nil,
          legend: String.t() | nil,
          help: String.t() | nil,
          gap: atom() | integer() | nil,
          align: atom() | nil,
          justify: atom() | nil,
          width: integer() | atom() | nil,
          height: integer() | atom() | nil,
          columns: integer() | nil,
          rows: integer() | nil,
          table_columns: keyword() | list() | nil,
          table_rows: list() | nil,
          empty_state: String.t() | nil,
          tree_nodes: list() | nil,
          log_entries: list() | nil,
          show_timestamps?: boolean() | nil,
          wrap?: boolean() | nil,
          severity: atom() | nil,
          current: integer() | float() | nil,
