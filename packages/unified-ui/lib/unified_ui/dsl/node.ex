            emphasis: nil,
            external?: nil,
            target_kind: nil,
            orientation: nil,
            decorative?: nil,
            size: nil,
            grow: nil,
            placeholder: nil,
            multiline?: nil,
            input_mode: nil,
            options: [],
            active_item: nil,
